/* ============================================================
   NEW!!! "What's New" pop-up — generated by alanwang.info/tools/whats-new
   Edit tools/whats-new/updates.json and run `node tools/whats-new/apply.js`,
   don't edit this copy by hand.

   Safe by design:
   - everything lives in a Shadow DOM, so its styles can't change the page
     and the page's styles can't break it;
   - while it's open, keys/clicks are stopped from reaching the game;
   - it shows once per version (remembered in this browser), add
     ?whatsnew to the address to see it again;
   - if anything goes wrong it quietly does nothing.
   ============================================================ */
(function () {
  "use strict";
  var C = {
  "id": "bucktycoon",
  "name": "Buck Tycoon",
  "emoji": "💵",
  "accent": "#ffd23f",
  "version": "V.1.3",
  "previous": "V.1.2",
  "date": "2 November 2026",
  "lead": "Your empire just got an update, boss!",
  "changes": [
    "NEW!!! This What's New pop-up: every update now tells you what changed",
    "A new README on GitHub explaining how to play"
  ],
  "earlier": [
    {
      "version": "V.1.2",
      "items": [
        "Version number shown in the corner of the screen"
      ]
    }
  ],
  "fun": [
    "Items you place in a shop's yard store up bucks for you",
    "Picking an item back up collects its stored bucks automatically",
    "Changed your mind? The SELL zone gives you half the price back"
  ],
  "tip": "Press Esc to stash what you're carrying back in your backpack.",
  "button": "Make it rain! ▶"
};
  try {
    var KEY = "whatsNew." + C.id;
    var force = /[?&#]whatsnew\b/i.test(location.search + location.hash);
    var seen = false;
    try { seen = localStorage.getItem(KEY) === C.version; } catch (e) { /* storage blocked: just show it */ }
    if (seen && !force) return;
  } catch (e) { return; }

  function esc(s) {
    return String(s).replace(/[&<>"]/g, function (c) { return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]; });
  }
  function list(items) {
    return "<ul>" + items.map(function (x) { return "<li>" + esc(x) + "</li>"; }).join("") + "</ul>";
  }
  function section(icon, title, body) {
    return '<section><h3><span aria-hidden="true">' + icon + "</span> " + esc(title) + "</h3>" + body + "</section>";
  }

  var CSS =
    ":host{all:initial}" +
    "*{box-sizing:border-box;margin:0;padding:0}" +
    ".back{position:fixed;inset:0;display:flex;align-items:center;justify-content:center;padding:16px;" +
    "background:rgba(4,7,18,.72);backdrop-filter:blur(4px);-webkit-backdrop-filter:blur(4px);" +
    "font:15px/1.5 system-ui,-apple-system,'Segoe UI',Roboto,sans-serif;color:#eef2ff;animation:fade .25s ease}" +
    ".card{position:relative;width:100%;max-width:540px;max-height:calc(100vh - 32px);display:flex;flex-direction:column;color-scheme:dark;" +
    "background:linear-gradient(160deg,#141b34,#0b1022);border:2px solid ACCENT;border-radius:18px;" +
    "box-shadow:0 0 0 1px rgba(255,255,255,.06),0 20px 60px rgba(0,0,0,.6),0 0 40px ACCENT55;" +
    "padding:22px 22px 16px;animation:pop .35s cubic-bezier(.2,1.4,.4,1)}" +
    ".body{overflow:auto;min-height:0;flex:1 1 auto;margin-right:-8px;padding-right:8px;scrollbar-color:ACCENT88 transparent}" +
    ".foot-bar{flex:0 0 auto;padding-top:4px}" +
    ".x{position:absolute;top:10px;right:10px;width:36px;height:36px;border-radius:50%;border:0;cursor:pointer;" +
    "background:rgba(255,255,255,.08);color:#fff;font:700 18px/36px system-ui,sans-serif}" +
    ".x:hover,.x:focus-visible{background:rgba(255,255,255,.18);outline:2px solid ACCENT}" +
    ".new{display:inline-block;font:900 13px/1 system-ui,sans-serif;letter-spacing:2px;color:#111;" +
    "background:linear-gradient(90deg,#ffe066,ACCENT,#ffe066);background-size:200% 100%;" +
    "padding:6px 10px;border-radius:999px;animation:shine 2.5s linear infinite}" +
    "h2{font:800 24px/1.2 system-ui,sans-serif;margin:12px 40px 6px 0}" +
    ".meta{display:flex;flex-wrap:wrap;gap:8px;align-items:center;margin-bottom:14px;color:#aab4d4;font-size:13px}" +
    ".ver{font:700 13px/1 ui-monospace,Consolas,monospace;color:#fff;background:ACCENT33;border:1px solid ACCENT;" +
    "padding:5px 9px;border-radius:8px}" +
    ".was{text-decoration:line-through;opacity:.7}" +
    "p.lead{margin-bottom:12px;color:#dfe6ff}" +
    "section{background:rgba(255,255,255,.04);border:1px solid rgba(255,255,255,.08);border-radius:12px;" +
    "padding:12px 14px;margin:10px 0}" +
    "h3{font:700 15px/1.3 system-ui,sans-serif;margin-bottom:6px;color:#fff}" +
    "ul{padding-left:20px}li{margin:4px 0}" +
    ".old{font-size:13px;color:#c3cbe6}.old b{color:#fff}" +
    ".go{display:block;width:100%;margin-top:10px;padding:12px;border:0;border-radius:12px;cursor:pointer;" +
    "font:800 16px/1 system-ui,sans-serif;color:#0a0f1f;background:ACCENT}" +
    ".go:hover,.go:focus-visible{filter:brightness(1.12);outline:2px solid #fff}" +
    ".foot{margin-top:8px;text-align:center;font-size:12px;color:#8a95b8}" +
    "@keyframes fade{from{opacity:0}}" +
    "@keyframes pop{from{transform:scale(.85);opacity:0}}" +
    "@keyframes shine{to{background-position:-200% 0}}" +
    "@media (prefers-reduced-motion:reduce){.back,.card,.new{animation:none}}";
  CSS = CSS.replace(/ACCENT(\d\d)?/g, function (m, a) { return a ? C.accent + a : C.accent; });

  var html =
    '<div class="back" part="backdrop"><div class="card" role="dialog" aria-modal="true" aria-labelledby="wn-title">' +
    '<button class="x" type="button" aria-label="Close">✕</button>' +
    '<div class="body"><span class="new">✨ NEW!!! UPDATE ✨</span>' +
    '<h2 id="wn-title">' + esc(C.emoji + " " + C.name) + "</h2>" +
    '<div class="meta"><span class="ver">' + esc(C.version) + "</span>" +
    (C.previous ? '<span>was <span class="was">' + esc(C.previous) + "</span></span>" : "") +
    (C.date ? "<span>· " + esc(C.date) + "</span>" : "") + "</div>" +
    (C.lead ? '<p class="lead">' + esc(C.lead) + "</p>" : "") +
    section("🆕", "What's new in " + C.version, list(C.changes || [])) +
    ((C.earlier && C.earlier.length)
      ? section("📜", "Earlier updates", '<div class="old">' + C.earlier.map(function (u) {
          return "<p><b>" + esc(u.version) + ":</b> " + esc(u.items.join(" · ")) + "</p>";
        }).join("") + "</div>")
      : "") +
    ((C.fun && C.fun.length) ? section("🎉", C.funTitle || "Fun facts", list(C.fun)) : "") +
    (C.tip ? section("💡", "Tip", "<p>" + esc(C.tip) + "</p>") : "") +
    "</div>" +
    '<div class="foot-bar"><button class="go" type="button">' + esc(C.button || "Let's go! ▶") + "</button>" +
    '<p class="foot">This shows once for each new version.</p></div>' +
    "</div></div>";

  var KEYS = ["keydown", "keyup", "keypress"];
  var POINTER = ["mousedown", "mouseup", "click", "dblclick", "contextmenu", "pointerdown", "pointerup",
    "pointermove", "mousemove", "touchstart", "touchmove", "touchend", "wheel"];

  function show() {
    if (document.getElementById("whats-new-popup")) return;
    var host = document.createElement("div");
    host.id = "whats-new-popup";
    host.setAttribute("style", "position:fixed;inset:0;z-index:2147483647;display:block");
    var root = host.attachShadow ? host.attachShadow({ mode: "open" }) : host;
    root.innerHTML = "<style>" + CSS + "</style>" + html;
    var closed = false;

    // keys: stop them before the game sees them (Escape closes; Enter/Space still press our buttons)
    function keyGuard(e) {
      if (closed) {
        // closed with a key: swallow that key's keyup too, then step aside for good
        if (e.type === "keyup") unguard();
      } else if (e.type === "keydown" && (e.key === "Escape" || e.key === "Esc")) { e.preventDefault(); close(true); }
      e.stopImmediatePropagation();
      e.stopPropagation();
    }
    function unguard() { KEYS.forEach(function (t) { window.removeEventListener(t, keyGuard, true); }); }
    // clicks/touches on the pop-up never reach the page underneath
    function pointerGuard(e) { e.stopPropagation(); }

    function close(byKey) {
      if (closed) return;
      closed = true;
      try { localStorage.setItem("whatsNew." + C.id, C.version); } catch (e) { /* fine */ }
      if (byKey) setTimeout(unguard, 1500); // in case the keyup never comes
      else unguard();
      if (host.parentNode) host.parentNode.removeChild(host);
      try { if (document.activeElement && document.activeElement.blur) document.activeElement.blur(); } catch (e) { /* fine */ }
    }
    // a button "clicked" by Enter/Space has e.detail === 0
    function closeBtn(e) { close(!!e && e.detail === 0); }

    KEYS.forEach(function (t) { window.addEventListener(t, keyGuard, true); });
    POINTER.forEach(function (t) { host.addEventListener(t, pointerGuard, false); });
    root.querySelector(".x").addEventListener("click", closeBtn);
    root.querySelector(".go").addEventListener("click", closeBtn);
    root.querySelector(".back").addEventListener("click", function (e) { if (e.target === this) close(false); });

    document.body.appendChild(host);
    try { root.querySelector(".go").focus({ preventScroll: true }); } catch (e) { /* fine */ }
  }

  function start() { try { show(); } catch (e) { /* never break the page */ } }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", start);
  else start();
})();
